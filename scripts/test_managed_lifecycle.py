#!/usr/bin/env python3
"""Opt-in real systemd user-service + encrypted harness lifecycle.

Temporary state and unused loopback ports only. No provider or Tailscale account.
Requires a functioning systemd user manager and already-enabled lingering.
"""
import importlib.util
import os
from pathlib import Path
import shlex
import socket
import subprocess
import tempfile
import time
import urllib.request

SCRIPT = Path(__file__).resolve().with_name("managed-runtime.py")
spec = importlib.util.spec_from_file_location("managed_runtime", SCRIPT)
runtime = importlib.util.module_from_spec(spec)
spec.loader.exec_module(runtime)


def main():
    target = Path(os.environ.get("CARGO_TARGET_DIR", SCRIPT.parent.parent / "target")).resolve()
    harness = target / "debug/examples/remote_access_harness"
    if not harness.is_file():
        raise RuntimeError("Build remote_access_harness before this test")
    with tempfile.TemporaryDirectory(prefix="aegis-managed-lifecycle-") as directory:
        base = Path(directory)
        root = base / "checkout with spaces"
        root.mkdir()
        state = base / "state"
        with socket.socket() as reservation:
            reservation.bind(("127.0.0.1", 0))
            port = reservation.getsockname()[1]
        db = state / "memory.db"
        (root / ".env").write_text(f"MEMORY_DB_PATH={db}\nAXUM_PORT={port}\nOAUTH_CALLBACK_PORT={port}\n")
        bundle = root / "webapp/dist/index.html"
        bundle.parent.mkdir(parents=True)
        bundle.write_text("<!doctype html><title>Managed lifecycle fixture</title>")
        launcher = root / "runtime"
        launcher.write_text("#!/bin/sh\nexport AEGIS_WEBAPP_DIR=" + shlex.quote(str(bundle.parent)) +
                            "\nexec " + " ".join(map(shlex.quote, [str(harness), str(db), str(port)])) + "\n")
        launcher.chmod(0o700)
        os.environ.update(AEGIS_RUNTIME_ROOT=str(root), AEGIS_RUNTIME_STATE_DIR=str(state),
                          AEGIS_RUNTIME_BIN=str(launcher), AEGIS_RUNTIME_START_TIMEOUT="30")
        os.environ.pop("AEGIS_RUNTIME_DB_KEY_HEX", None)
        os.environ.pop("AEGIS_RUNTIME_DB_KEY_FILE", None)
        app = runtime.Installation()
        app.preflight(True)
        key_path, key = app.key(True)
        installed = False
        try:
            app.install()
            installed = True
            # The installer process exits before checking its service.
            subprocess.run(["python3", str(SCRIPT), "start"], check=True, timeout=60)
            def pid():
                return runtime.run(["systemctl", "--user", "show", app.unit, "-p", "MainPID", "--value"]).stdout.strip()
            first_pid = pid()
            with urllib.request.urlopen(app.urls()[0], timeout=5) as response:
                assert response.status == 200
            print("PASS: actual systemd-owned service survives installer-process exit")
            assert db.read_bytes()[:16] != b"SQLite format 3\0"
            runtime.run(["systemctl", "--user", "kill", "--signal=SIGKILL", app.unit])
            time.sleep(6)
            app.wait_ready()
            assert pid() not in ("0", first_pid)
            print("PASS: crash recovery starts a new real service process with the saved key")
            app.control("stop")
            original_db = db.read_bytes()
            key_path.write_text("0" * 64 + "\n")
            os.environ["AEGIS_RUNTIME_START_TIMEOUT"] = "4"
            try:
                app.control("start")
            except RuntimeError:
                pass
            else:
                raise AssertionError("wrong key was accepted")
            app.control("stop")
            assert db.read_bytes() == original_db
            print("PASS: wrong key fails startup and preserves the encrypted database")
            key_path.write_text(key + "\n")
            os.environ["AEGIS_RUNTIME_START_TIMEOUT"] = "30"
            app.control("start")
            print("PASS: restoring the original key restores service without resetting data")
        finally:
            if installed:
                app.control("remove")
                assert db.exists() and key_path.exists()
                print("PASS: removal stops only the test unit and retains state/key")
            # These paths were generated by this test, never existing user data.
            key_path.unlink(missing_ok=True)
            if app.directory.exists():
                app.directory.rmdir()


if __name__ == "__main__":
    main()
